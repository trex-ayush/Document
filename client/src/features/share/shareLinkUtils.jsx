/** Small helpers shared by every "send this link" screen (share links, member invites). */

/** Copies `text`; falls back to selecting the given input + execCommand for older/insecure browsers. */
export async function copyText(text, inputEl) {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // fall through to the legacy path
  }
  try {
    if (inputEl) {
      inputEl.focus();
      inputEl.select();
      inputEl.setSelectionRange(0, text.length);
      return document.execCommand('copy');
    }
  } catch {
    // ignore
  }
  return false;
}

